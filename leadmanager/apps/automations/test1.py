def create_or_update_lead_step(crm_update, source):
    """
    Create or update the lead/opportunity in Odoo based on the crm_update generated by the agent, and create the contact (res.partner) if it does not exist.

    Corre en cada mensaje, no solo al escalar: así el lead en Odoo se
    mantiene al día con cada interacción. El tipo de registro lo decide
    create_or_update_lead según crm_update['escalar_a_humano']:

      - False -> se crea/mantiene como 'lead'
      - True  -> se crea como 'opportunity' (o se promueve si ya existía
                 como lead abierto) y se asigna a ctx['odoo']['seller_uid']

    Si no hay respuesta generada (parseo fallido en el paso anterior), no
    hay crm_update que registrar y el step no hace nada.
    """

    response_to_prospect = ctx.get("response_to_prospect")
    crm_update = response_to_prospect.get(
        "crm_update")

    if crm_update['escalar_a_humano'] == True:

        crm_update = response_to_prospect.get("crm_update", {})
        person = ctx.get("person", {}).get("data", {})
        source = ctx.get("source")
        identifier = ctx.get("source_identifier")
        seller_id = ctx.get("odoo", {}).get("seller_id", None)
        company_id = ctx.get("odoo", {}).get("company_id", None)

        result = create_or_update_lead(
            crm_update=crm_update,
            source=source,
            person=person,
            identifier=identifier,
            seller_id=seller_id,
            company_id=company_id
        )


create_or_update_lead_step(ctx, source='email')
